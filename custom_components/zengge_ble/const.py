# Map hardware telemetry (mode_id, sub_mode_id) -> fallback effect name for Carrier-Wave devices
CARRIER_WAVE_MODE_TO_DEFAULT_NAME: dict[tuple[int, int], str] = {
    (0x24, 0x01): "Preset Red & Green",
}
for _eff_name, (_prefix, _tail) in CARRIER_WAVE_EFFECT_TEMPLATES.items():
    _sub = int(_tail[:2], 16)
    if _prefix == "E12100":
        CARRIER_WAVE_MODE_TO_DEFAULT_NAME.setdefault((0x25, _sub), _eff_name)
    elif _prefix == "EC0300":
        CARRIER_WAVE_MODE_TO_DEFAULT_NAME.setdefault((0x62, _sub), _eff_name)
